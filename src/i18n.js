let LANG = "en";
export const getLang = () => LANG;
export const setLang = (l) => { LANG = l; };
// Inline pair for texts that exist only in one place (help, labels of the new views)
export const L = (en, de) => (LANG === "de" ? de : en);
export const t = (s) => (LANG === "de" ? DE[s] ?? s : s);
// Text with {placeholders}
export const tf = (s, vars = {}) => t(s).replace(/\{(\w+)\}/g, (_, k) => (vars[k] === undefined ? "" : String(vars[k])));

export function fmt(x) {
  return x.toLocaleString(LANG === "de" ? "de-DE" : "en-US", { maximumFractionDigits: 2, minimumFractionDigits: 2 });
}
